/** Libellé selon la langue, pour les petits textes des captures d'écran. */
export const useLangue = () => {
  const { i18n } = useTranslation();
  // Petits textes des captures : français, sinon anglais pour toutes les autres langues.
  const francais = langueDe(i18n.language).code === "fr";
  return (texteFr: string, texteEn: string) => (francais ? texteFr : texteEn);
};

